import type { NextConfig } from "next";

/**
 * Hardened HTTP response headers applied to every route.
 *
 * NOTE: kept intentionally "preview-friendly" for the sandbox environment:
 * - No X-Frame-Options / frame-ancestors restriction (the preview panel
 *   embeds this app in an iframe and would be blocked otherwise).
 * - No upgrade-insecure-requests / HSTS (would force HTTPS and break
 *   plain-HTTP previews).
 * All other hardening stays in place.
 */
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value:
      "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()",
  },
  { key: "X-DNS-Prefetch-Control", value: "on" },
  {
    key: "Content-Security-Policy",
    value: [
      "default-src 'self'",
      "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
      "style-src 'self' 'unsafe-inline'",
      "img-src 'self' data: blob: https:",
      "font-src 'self' data:",
      "connect-src 'self' https: ws: wss:",
      "object-src 'none'",
      "base-uri 'self'",
      "form-action 'self'",
    ].join("; "),
  },
];

const nextConfig: NextConfig = {
  output: "standalone",
  poweredByHeader: false,
  // Allow the sandbox preview panel origin to load /_next/* dev resources.
  allowedDevOrigins: ["*.space-z.ai", "space-z.ai"],
  /* config options here */
  typescript: {
    ignoreBuildErrors: true,
  },
  reactStrictMode: false,
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
